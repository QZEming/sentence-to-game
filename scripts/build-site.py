def prepare_output(root, output):
    protected = [root, root / "games", root / "templates", root / "scripts", root / ".github", root / ".git"]
    if any(output == path or output in path.parents for path in protected):
        raise ValueError(f"输出路径不能覆盖仓库或源码目录：{output}")
    if any(path in output.parents for path in protected[1:]):
        raise ValueError(f"输出路径不能位于源码或仓库配置目录中：{output}")
    if output.exists():
        marker = output / BUILD_MARKER
        if any(output.iterdir()) and (
            not marker.is_file()
            or marker.read_text(encoding="utf-8") != BUILD_MARKER_CONTENT
        ):
            raise ValueError(f"输出目录不是本脚本生成的站点，请使用空目录：{output}")
        shutil.rmtree(output)
    output.mkdir(parents=True)
    (output / BUILD_MARKER).write_text(BUILD_MARKER_CONTENT, encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1], help="Repository root")
    parser.add_argument("--output", type=Path, help="Output directory; relative paths are resolved from the repository root (default: docs)")
    args = parser.parse_args()
    root = args.root.resolve()
    output = args.output or Path("docs")
    if not output.is_absolute():
        output = root / output
    if output.is_symlink():
        parser.exit(1, f"构建失败：输出目录不能是符号链接：{output}\n")
    output = output.resolve()
    try:
        games = discover_games(root)
        prepare_output(root, output)
        for game, source, _ in games:
            copy_web_files(source, output / "games" / game.name)
        (output / "index.html").write_text(render_index(games), encoding="utf-8")
        (output / ".nojekyll").touch()
    except (OSError, UnicodeError, ValueError) as error:
        parser.exit(1, f"构建失败：{error}\n")
    print(f"已构建 {len(games)} / 100 个游戏：{output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
