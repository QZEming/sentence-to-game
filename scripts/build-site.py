from pathlib import Path
from urllib.parse import quote


REPOSITORY_URL = "https://github.com/QZEming/sentence-to-game"
GAME_DIRECTORY = re.compile(r"^\d{3}-[a-z0-9]+(?:-[a-z0-9]+)*$")
BUILD_MARKER = ".sentence-to-game-build"
BUILD_MARKER_CONTENT = "Generated by scripts/build-site.py\n"
EXCLUDED_DIRECTORIES = {"node_modules", "__pycache__", "venv"}
EXCLUDED_FILES = {
    "id_rsa", "id_ed25519", "credentials", "credentials.json",
    "secrets.json", "package-lock.json", "pnpm-lock.yaml", "yarn.lock",
}
EXCLUDED_SUFFIXES = {".pem", ".key", ".p12", ".pfx", ".keystore", ".pyc"}


def excluded(path):
    name = path.name.lower()
    return (
        name.startswith(".")
        or name in EXCLUDED_DIRECTORIES
        or name in EXCLUDED_FILES
        or path.suffix.lower() in EXCLUDED_SUFFIXES
    )


def game_title(game):
    readme = game / "README.md"
    if readme.is_file():
        for line in readme.read_text(encoding="utf-8").splitlines():
            match = re.match(r"^#\s+(.+?)\s*#*\s*$", line)
            if match:
                return match.group(1)
    return game.name.split("-", 1)[1].replace("-", " ")


def discover_games(root):
    games = []
    games_directory = root / "games"
    if not games_directory.is_dir():
        return games
    for game in sorted(games_directory.iterdir()):
        if not GAME_DIRECTORY.fullmatch(game.name):
            continue
        if game.is_symlink():
            raise ValueError(f"游戏目录不能是符号链接：{game}")
        if not game.is_dir():
            continue
        source = next(
            (game / folder for folder in ("dist", "src")
             if (game / folder / "index.html").is_file()),
            None,
        )
        if source is None:
            raise ValueError(
                f"游戏 {game.name} 缺少静态入口：请提供 "
                "dist/index.html 或 src/index.html。需要构建的项目请先生成 dist/。"
            )
        if source.is_symlink() or (source / "index.html").is_symlink():
            raise ValueError(f"游戏入口不能是符号链接：{source / 'index.html'}")
        games.append((game, source, game_title(game)))
    return games


def copy_web_files(source, destination):
    destination.mkdir(parents=True, exist_ok=True)
    for item in sorted(source.iterdir()):
        if excluded(item):
            continue
        if item.is_symlink():
            raise ValueError(f"发布资源不能是符号链接：{item}")
        target = destination / item.name
        if item.is_dir():
            copy_web_files(item, target)
        elif item.is_file():
            shutil.copy2(item, target)


